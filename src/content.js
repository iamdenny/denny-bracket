export function passageFor(lang, preset = {}) {
  if (preset.level === "numbers")
    return Array.from(
      { length: 30 },
      (_, i) => `${10 + i} ${100 + i * 7} ${2026 + i} ${(i % 12) + 1}/23`,
    ).join(" ");
  if (preset.level === "beginner")
    return {
      en: "we can learn one word at a time and find our own way ",
      ko: "우리 함께 한 걸음 두 걸음 천천히 연습해 봐요 ",
      ja: "あいうえお かきくけこ さしすせそ たちつてと ",
      es: "paso a paso podemos aprender y encontrar nuestro ritmo ",
    }[lang].repeat(20);
  let index = preset.daily ? Math.floor(Date.now() / 86400000) % 4 : 0;
  const text = paragraphs[lang][index];
  if (preset.level === "punctuation")
    return (text + ' "Hello!" (2026): 10, 20, 30; 50%? ').repeat(8);
  return [...paragraphs[lang].slice(index), ...paragraphs[lang].slice(0, index)]
    .join(" ")
    .concat(" ")
    .repeat(5);
}
